class Translator:
    def __init__(self, lang="pt"):
        self.lang = lang if lang in STRINGS else "pt"

    def set_lang(self, lang):
        if lang in STRINGS:
            self.lang = lang

    def t(self, key, **kwargs):
        value = STRINGS.get(self.lang, STRINGS["pt"]).get(key, key)
        if kwargs:
            try:
                return value.format(**kwargs)
            except Exception:
                return value
        return value
